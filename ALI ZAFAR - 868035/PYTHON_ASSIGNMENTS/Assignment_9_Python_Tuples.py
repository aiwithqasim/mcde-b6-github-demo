from operator import itemgetter

records = (
    ("Laptop", 120000, 5),
    ("Mouse", 1500, 20),
    ("Keyboard", 3500, 10)
)

inventory_prod = (
    (records[0][1] * records[0][2]) +
    (records[1][1] * records[1][2]) +
    (records[2][1] * records[2][2])
)

# 2. Most Expensive Product Name
expensive_prod = max(records, key=itemgetter(1))[0]

# 3. Reversed Tuple of Names
names = (records[0][0], records[1][0], records[2][0])
reversed_names = names[::-1]

