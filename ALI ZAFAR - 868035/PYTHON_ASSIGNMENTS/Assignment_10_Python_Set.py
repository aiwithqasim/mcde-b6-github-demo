# 1. All Three (.intersection)
all_three = python.intersection(sql, aws)

# 2. Exactly Python and SQL, not AWS (.intersection & .difference)
python_sql_only = python.intersection(sql).difference(aws)

# 3. At least Two (.union & .intersection)
at_least_two = python.intersection(sql).union(sql.intersection(aws), python.intersection(aws))

