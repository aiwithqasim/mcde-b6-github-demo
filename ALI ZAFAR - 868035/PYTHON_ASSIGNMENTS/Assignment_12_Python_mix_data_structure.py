# Q41. Student Performance System

students = [
    {"id": 1, "name": "Ali", "marks": (85, 90, 88)},
    {"id": 2, "name": "Sara", "marks": (92, 95, 91)},
    {"id": 3, "name": "Ahmed", "marks": (78, 84, 80)}
]

avg1 = sum(students[0]["marks"]) / len(students[0]["marks"])
avg2 = sum(students[1]["marks"]) / len(students[1]["marks"])
avg3 = sum(students[2]["marks"]) / len(students[2]["marks"])

averages = {
    students[0]["name"]: avg1,
    students[1]["name"]: avg2,
    students[2]["name"]: avg3
}

top_student = max(averages, key=averages.get)

names = (
    students[0]["name"],
    students[1]["name"],
    students[2]["name"]
)

unique_marks = set(
    students[0]["marks"]
    + students[1]["marks"]
    + students[2]["marks"]
)

print("Averages:", averages)
print("Top student:", top_student)
print("Names:", names)
print("Unique marks:", unique_marks)

