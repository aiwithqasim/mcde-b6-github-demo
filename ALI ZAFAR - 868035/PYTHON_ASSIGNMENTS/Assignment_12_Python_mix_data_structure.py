# Q50. Final Company Analysis
company = {
    "departments": {
        "Engineering": {
            "employees": [
                ("Ali", 120000, {"Python", "AWS", "SQL"}),
                ("Sara", 150000, {"Python", "Databricks", "SQL"})
            ],
            "budget": 500000
        },
        "Analytics": {
            "employees": [
                ("Ahmed", 100000, {"SQL", "Power BI"}),
                ("Zain", 130000, {"Python", "SQL", "Tableau"})
            ],
            "budget": 400000
        }
    }
}

eng = company["departments"]["Engineering"]
ana = company["departments"]["Analytics"]

e1 = eng["employees"][0]
e2 = eng["employees"][1]
a1 = ana["employees"][0]
a2 = ana["employees"][1]

eng_payroll = e1[1] + e2[1]
ana_payroll = a1[1] + a2[1]
company_payroll = eng_payroll + ana_payroll

employees = (e1, e2, a1, a2)
highest_paid = max(employees, key=lambda employee: employee[1])

shared_skills = (
    e1[2] & e2[2] & a1[2] & a2[2]
)

engineering_only = (
    e1[2] | e2[2]
) - (
    a1[2] | a2[2]
)

remaining_budget = {
    "Engineering": eng["budget"] - eng_payroll,
    "Analytics": ana["budget"] - ana_payroll
}

eng_average = eng_payroll / len(eng["employees"])
ana_average = ana_payroll / len(ana["employees"])

higher_average = (
    "Engineering" if eng_average > ana_average
    else "Analytics" if ana_average > eng_average
    else "Equal"
)

name_salary = {
    e1[0]: e1[1],
    e2[0]: e2[1],
    a1[0]: a1[1],
    a2[0]: a2[1]
}

all_skills = (
    e1[2] | e2[2] | a1[2] | a2[2]
)

combined_budget = eng["budget"] + ana["budget"]
budget_sufficient = combined_budget >= company_payroll

print("Department payroll:", {
    "Engineering": eng_payroll,
    "Analytics": ana_payroll
})
print("Company payroll:", company_payroll)
print("Highest-paid:", highest_paid[0], highest_paid[1])
print("Skills shared by all:", shared_skills)
print("Engineering-only skills:", engineering_only)
print("Remaining budgets:", remaining_budget)
print("Higher average salary:", higher_average)
print("Name-to-salary:", name_salary)
print("All unique skills:", all_skills)
print("Combined budget sufficient:", budget_sufficient)