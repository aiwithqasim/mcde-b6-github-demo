# Q40. Inventory Management
inventory = {
    "P101": {"name": "Laptop", "price": 120000, "stock": 5},
    "P102": {"name": "Mouse", "price": 1500, "stock": 20},
    "P103": {"name": "Keyboard", "price": 3500, "stock": 10}
}

# TOTAL VALUE (Multiplication sign '*' add kar diya hai)
p101_invn = inventory["P101"]["price"] * inventory["P101"]["stock"]
p102_invn = inventory["P102"]["price"] * inventory["P102"]["stock"]
p103_invn = inventory["P103"]["price"] * inventory["P103"]["stock"]

total_invn = p101_invn + p102_invn + p103_invn


# MOST VALUABLE ITEM BY (price * stock)
# Values ki ek choti dictionary bana li taake max() sahi item dhoond sake
item_values = {
    "P101": p101_invn,
    "P102": p102_invn,
    "P103": p103_invn
}
most_valuable = max(item_values, key=item_values.get)


# UPDATE STOCK (2 laptops aur 5 mice bikne ke baad stock kam karna)
inventory["P101"]["stock"] -= 2  # Laptop stock: 5 - 2 = 3
inventory["P102"]["stock"] -= 5  # Mouse stock: 20 - 5 = 15


# Print results
print(f"Total Inventory Value: {total_invn}")
print(f"Most Valuable Item Key: {most_valuable} ({inventory[most_valuable]['name']})")
print(f"Updated Laptop Stock: {inventory['P101']['stock']}")
print(f"Updated Mouse Stock: {inventory['P102']['stock']}")